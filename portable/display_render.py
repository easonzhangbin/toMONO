"""Explicit preview color management and optional, reversible Adobe rendering.

The point curve is our measured calibration, not a RAW transfer function. It
only sets an initial Adobe development appearance; scene-linear samples stay
untouched. Calibration evidence: analysis/outputs/tone_consistency_8485ce18.
"""
import struct,zlib
from xml.sax.saxutils import quoteattr
import numpy as np

APPEARANCE_ID='tomono-reference-v1'
# Measured with a generated linear wedge, neutral sliders and sharpening off.
# Adobe accepts at most 16 point-curve entries; larger lists can be ignored.
REFERENCE_POINTS=((0,0),(4,7),(8,12),(15,20),(26,30),(41,41),(61,54),(87,70),
                  (117,88),(148,106),(178,127),(204,151),(222,173),(237,198),(247,222),(255,255))

def srgb_encode(v):
    return np.where(v<=0.0031308,12.92*v,1.055*np.maximum(v,0)**(1/2.4)-0.055)

def srgb_decode(v):
    return np.where(v<=0.04045,v/12.92,((v+0.055)/1.055)**2.4)

def reference_points(gamma=2.2):
    # Preview gamma is a display adjustment in a fixed gamma-2.2 space, not a
    # change to the RAW encoding. Carry that appearance when matching is on.
    points=np.array(REFERENCE_POINTS,dtype=float)
    points[:,1]=np.rint(srgb_encode(srgb_decode(points[:,1]/255)**(2.2/gamma))*255)
    points[0]=(0,0);points[-1]=(255,255)
    return [(int(x),int(y)) for x,y in points]

def output_camera_model(value):
    """Mark derived RAWs without truncating or impersonating a native camera.

    Forty characters is a display-length policy, not an EXIF format limit.
    """
    value=str(value).strip() or 'RAW Camera'
    if value.endswith((' MONOCHROME',' toMONO')):return value
    return value+(' MONOCHROME' if len(value)+11<=40 else ' toMONO')

def adobe_reference_xmp(gamma=2.2):
    return dng_xmp(gamma,True)

def dng_xmp(gamma=2.2,match_preview=True,source_identity=None):
    settings={'Version':'13.0','ProcessVersion':'11.0','HasSettings':'True',
        'Sharpness':'0','LuminanceSmoothing':'0','ColorNoiseReduction':'0',
        'Exposure2012':'0','Contrast2012':'0','Highlights2012':'0','Shadows2012':'0',
        'Whites2012':'0','Blacks2012':'0','Texture':'0','Clarity2012':'0','Dehaze':'0',
        'ParametricShadows':'0','ParametricDarks':'0','ParametricLights':'0','ParametricHighlights':'0',
        'GrainAmount':'0','PostCropVignetteAmount':'0','LensProfileEnable':'0',
        'ToneCurveName2012':'Custom'}
    attrs=' '.join('crs:'+k+'="'+v+'"' for k,v in settings.items()) if match_preview else ''
    provenance=''
    if source_identity:
        provenance=' xmlns:tm="urn:tomono:metadata:1.0" '+ ' '.join(
            'tm:Source'+key+'='+quoteattr(str(source_identity.get(key,'')))
            for key in ('Make','Model','UniqueCameraModel'))
    curve=''.join(f'<rdf:li>{x}, {y}</rdf:li>' for x,y in reference_points(gamma))
    curve=('<crs:ToneCurvePV2012><rdf:Seq>'+curve+'</rdf:Seq></crs:ToneCurvePV2012>') if match_preview else ''
    return ('<?xpacket begin="\ufeff" id="W5M0MpCehiHzreSzNTczkc9d"?>'
        '<x:xmpmeta xmlns:x="adobe:ns:meta/"><rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">'
        '<rdf:Description rdf:about="" xmlns:crs="http://ns.adobe.com/camera-raw-settings/1.0/" '+attrs+provenance+'>'
        +curve+
        '</rdf:Description></rdf:RDF></x:xmpmeta><?xpacket end="w"?>').encode('utf-8')

def preview_icc(rgb=False):
    """Small, original ICC v2 profiles with the same gamma in both previews."""
    u32=lambda n:struct.pack('>I',n)
    fixed=lambda v:struct.pack('>i',round(v*65536))
    xyz=lambda v:b'XYZ '+b'\0'*4+b''.join(fixed(x) for x in v)
    name=('toMONO RGB Gamma 2.2' if rgb else 'toMONO Gray Gamma 2.2').encode()+b'\0'
    desc=b'desc'+b'\0'*4+u32(len(name))+name+b'\0'*8+b'\0'*70
    trc=b'curv'+b'\0'*4+u32(1)+struct.pack('>H',round(2.2*256))
    tags=[(b'desc',desc),(b'cprt',b'text'+b'\0'*4+b'Generated by toMONO\0'),(b'wtpt',xyz((.9642,1,.8249)))]
    if rgb:
        tags += [(b'rXYZ',xyz((.4360747,.2225045,.0139322))),
                 (b'gXYZ',xyz((.3850649,.7168786,.0971045))),
                 (b'bXYZ',xyz((.1430804,.0606169,.7141733))),
                 (b'rTRC',trc),(b'gTRC',trc),(b'bTRC',trc)]
    else:tags += [(b'kTRC',trc)]
    offset=132+12*len(tags);records=b'';payload=b''
    for sig,data in tags:
        records+=sig+u32(offset)+u32(len(data));padding=b'\0'*(-len(data)%4)
        payload+=data+padding;offset+=len(data)+len(padding)
    header=bytearray(128)
    header[:4]=u32(offset);header[8:12]=bytes((2,0x10,0,0));header[12:16]=b'mntr'
    header[16:20]=b'RGB ' if rgb else b'GRAY';header[20:24]=b'XYZ '
    header[24:36]=struct.pack('>6H',2026,10,30,0,0,0);header[36:40]=b'acsp';header[40:44]=b'APPL'
    header[64:68]=u32(1);header[68:80]=b''.join(fixed(v) for v in (.9642,1,.8249));header[80:84]=b'toMO'
    return bytes(header)+u32(len(tags))+records+payload

def encode_preview_png(image):
    import imagecodecs
    png=imagecodecs.png_encode(image)
    payload=b'toMONO preview\0\0'+zlib.compress(preview_icc(rgb=image.ndim==3))
    chunk=b'iCCP'+payload
    # IHDR always ends at byte 33. Add an explicit profile before image data.
    return png[:33]+struct.pack('>I',len(payload))+chunk+struct.pack('>I',zlib.crc32(chunk))+png[33:]
